import { useState } from 'react';
import { useNavigate } from 'react-router';
import { useQueryClient } from '@tanstack/react-query';
import { CheckCircle2, CircleAlert, CircleX } from 'lucide-react';
import { api, ApiError, setCsrf } from '@/lib/api';
import { TIMEZONES } from '@/lib/utils';
import { Button } from '@/components/ui/button';
import { Card, CardContent } from '@/components/ui/card';
import { Field, Input, NativeSelect } from '@/components/ui/input';
import { Switch } from '@/components/ui/misc';
import { AuthLayout } from './AuthLayout';

interface Checks {
  environment: { key: string; ok: boolean; message: string }[];
  data_dir: { path: string; writable: boolean };
  database: { ok: boolean; latencyMs?: number; error?: string };
  migrations: { expected: number; applied: number; pending: string[] };
  chromium: { ok: boolean; version: string | null; path: string; error: string | null };
  defaults: { base_url: string; timezone: string };
}

const STEPS = ['Installation token', 'Environment & database', 'Administrator', 'Application', 'Security', 'Finish'];

function Row({ ok, warn, label, detail }: { ok: boolean; warn?: boolean; label: string; detail: string }) {
  const Icon = ok ? CheckCircle2 : warn ? CircleAlert : CircleX;
  return (
    <li className="flex items-start gap-2.5 py-2">
      <Icon className={ok ? 'mt-0.5 size-4 text-success' : warn ? 'mt-0.5 size-4 text-warning' : 'mt-0.5 size-4 text-danger'} />
      <div className="min-w-0">
        <p className="text-[13px] font-medium">{label}</p>
        <p className="break-all text-xs text-muted">{detail}</p>
      </div>
    </li>
  );
}

export function SetupPage() {
  const navigate = useNavigate();
  const qc = useQueryClient();
  const [step, setStep] = useState(0);
  const [token, setToken] = useState('');
  const [checks, setChecks] = useState<Checks | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [busy, setBusy] = useState(false);
  const [migrateOut, setMigrateOut] = useState<string | null>(null);
  const [admin, setAdmin] = useState({ name: '', email: '', password: '', confirm: '' });
  const [app, setApp] = useState({ base_url: location.origin, timezone: Intl.DateTimeFormat().resolvedOptions().timeZone });
  const [sec, setSec] = useState({ session_expiry_hours: 12, default_approval_policy: 'REQUIRE_APPROVAL', allow_dynamic_client_registration: true, login_max_attempts: 5 });

  const run = async (fn: () => Promise<void>) => {
    setBusy(true);
    setError(null);
    try {
      await fn();
    } catch (e) {
      setError(e instanceof ApiError ? e.message + (e.details?.problems ? ` — ${e.details.problems.join('; ')}` : '') : String(e));
    } finally {
      setBusy(false);
    }
  };

  const loadChecks = () => run(async () => {
    const c = await api.post<Checks>('/setup/checks', { token });
    setChecks(c);
    setApp((a) => ({ ...a, base_url: c.defaults.base_url || a.base_url }));
    setStep(1);
  });

  const envOk = checks && checks.database.ok && checks.data_dir.writable && checks.environment.filter((e) => e.key === 'APP_ENCRYPTION_KEY' || e.key === 'BASE_URL').every((e) => e.ok);
  const migrated = checks && checks.migrations.pending.length === 0 && checks.migrations.applied > 0;

  return (
    <AuthLayout wide>
      <Card>
        <CardContent className="p-5">
          <div className="mb-5">
            <h1 className="text-base font-semibold">Initial setup</h1>
            <p className="mt-1 text-[13px] text-muted">Step {step + 1} of {STEPS.length}: {STEPS[step]}</p>
            <ol className="mt-3 flex gap-1" aria-hidden>
              {STEPS.map((s, i) => <li key={s} className={`h-1 flex-1 rounded ${i <= step ? 'bg-primary' : 'bg-surface-2'}`} />)}
            </ol>
          </div>

          {step === 0 && (
            <form className="grid gap-4" onSubmit={(e) => { e.preventDefault(); void loadChecks(); }}>
              <p className="text-[13px] text-muted">
                Enter the one-time installation token. It was generated by <code>install.sh</code> (<code>SETUP_TOKEN</code> in <code>.env</code>) or written to <code>$DATA_DIR/setup-token</code> on first start.
              </p>
              <Field label="Installation token" htmlFor="token">
                <Input id="token" value={token} onChange={(e) => setToken(e.target.value.trim())} autoComplete="off" required />
              </Field>
              <div className="flex justify-end"><Button type="submit" disabled={busy || token.length < 8}>Continue</Button></div>
            </form>
          )}

          {step === 1 && checks && (
            <div className="grid gap-4">
              <ul className="divide-y rounded-md border px-3">
                {checks.environment.map((e, i) => <Row key={i} ok={e.ok} warn={!e.ok && e.key === 'CHROMIUM_DISABLE_SANDBOX'} label={e.key} detail={e.message} />)}
                <Row ok={checks.data_dir.writable} label="Data directory" detail={`${checks.data_dir.path} ${checks.data_dir.writable ? '(writable)' : '(not writable)'}`} />
                <Row ok={checks.database.ok} label="Database connectivity" detail={checks.database.ok ? `Connected (${checks.database.latencyMs} ms)` : checks.database.error ?? 'Failed'} />
                <Row ok={!!migrated} warn={!migrated} label="Database migrations" detail={`${checks.migrations.applied} applied, ${checks.migrations.pending.length} pending`} />
                <Row ok={checks.chromium.ok} label="Chromium" detail={checks.chromium.version ?? `${checks.chromium.path || 'not configured'} — ${checks.chromium.error}`} />
              </ul>
              {migrateOut && <pre className="max-h-40 overflow-auto rounded bg-surface-2 p-2 text-xs">{migrateOut}</pre>}
              <div className="flex flex-wrap justify-end gap-2">
                <Button variant="outline" onClick={loadChecks} disabled={busy}>Re-run checks</Button>
                {!migrated && checks.database.ok && (
                  <Button variant="secondary" disabled={busy} onClick={() => run(async () => {
                    const r = await api.post<{ ok: boolean; output: string }>('/setup/migrate', { token });
                    setMigrateOut(r.output);
                    const c = await api.post<Checks>('/setup/checks', { token });
                    setChecks(c);
                  })}>Apply migrations</Button>
                )}
                <Button disabled={!envOk || !migrated} onClick={() => setStep(2)}>Continue</Button>
              </div>
              {!checks.chromium.ok && <p className="text-xs text-warning">Chromium is required to connect WhatsApp accounts. You can finish setup and install it afterwards (see README).</p>}
            </div>
          )}

          {step === 2 && (
            <form className="grid gap-4" onSubmit={(e) => { e.preventDefault(); if (admin.password !== admin.confirm) return setError('Passwords do not match'); setError(null); setStep(3); }}>
              <p className="text-[13px] text-muted">Create the initial Super Administrator. No default passwords exist.</p>
              <Field label="Full name" htmlFor="an"><Input id="an" required value={admin.name} onChange={(e) => setAdmin({ ...admin, name: e.target.value })} /></Field>
              <Field label="Email" htmlFor="ae"><Input id="ae" type="email" required autoComplete="username" value={admin.email} onChange={(e) => setAdmin({ ...admin, email: e.target.value })} /></Field>
              <Field label="Password" htmlFor="ap" hint="At least 12 characters using three of: lowercase, uppercase, digits, symbols."><Input id="ap" type="password" autoComplete="new-password" required minLength={12} value={admin.password} onChange={(e) => setAdmin({ ...admin, password: e.target.value })} /></Field>
              <Field label="Confirm password" htmlFor="ac"><Input id="ac" type="password" autoComplete="new-password" required value={admin.confirm} onChange={(e) => setAdmin({ ...admin, confirm: e.target.value })} /></Field>
              <div className="flex justify-between"><Button variant="ghost" onClick={() => setStep(1)}>Back</Button><Button type="submit">Continue</Button></div>
            </form>
          )}

          {step === 3 && (
            <form className="grid gap-4" onSubmit={(e) => { e.preventDefault(); setStep(4); }}>
              <Field label="Application URL" htmlFor="bu" hint="Public HTTPS URL, e.g. https://whatsapp.techtixglobal.com. OAuth and MCP use BASE_URL from the environment."><Input id="bu" type="url" required value={app.base_url} onChange={(e) => setApp({ ...app, base_url: e.target.value })} /></Field>
              <Field label="Default timezone" htmlFor="tz">
                <NativeSelect id="tz" value={app.timezone} onChange={(e) => setApp({ ...app, timezone: e.target.value })}>
                  {TIMEZONES.map((t) => <option key={t}>{t}</option>)}
                </NativeSelect>
              </Field>
              <div className="flex justify-between"><Button variant="ghost" onClick={() => setStep(2)}>Back</Button><Button type="submit">Continue</Button></div>
            </form>
          )}

          {step === 4 && (
            <form className="grid gap-4" onSubmit={(e) => { e.preventDefault(); setStep(5); }}>
              <Field label="Session lifetime (hours)" htmlFor="se"><Input id="se" type="number" min={1} max={720} value={sec.session_expiry_hours} onChange={(e) => setSec({ ...sec, session_expiry_hours: Number(e.target.value) })} /></Field>
              <Field label="Failed sign-ins before lockout" htmlFor="la"><Input id="la" type="number" min={3} max={50} value={sec.login_max_attempts} onChange={(e) => setSec({ ...sec, login_max_attempts: Number(e.target.value) })} /></Field>
              <Field label="Default approval policy for new integrations" htmlFor="ap2">
                <NativeSelect id="ap2" value={sec.default_approval_policy} onChange={(e) => setSec({ ...sec, default_approval_policy: e.target.value })}>
                  <option value="REQUIRE_APPROVAL">Require approval before sending (recommended)</option>
                  <option value="READ_ONLY">Read-only</option>
                  <option value="DIRECT">Direct sending</option>
                </NativeSelect>
              </Field>
              <label className="flex items-center justify-between gap-3 rounded-md border p-3">
                <span>
                  <span className="block text-[13px] font-medium">Allow dynamic client registration</span>
                  <span className="block text-xs text-muted">Needed for ChatGPT and most MCP clients to register automatically. Every connection still requires a signed-in user's consent.</span>
                </span>
                <Switch checked={sec.allow_dynamic_client_registration} onCheckedChange={(v) => setSec({ ...sec, allow_dynamic_client_registration: v })} />
              </label>
              <div className="flex justify-between"><Button variant="ghost" onClick={() => setStep(3)}>Back</Button><Button type="submit">Continue</Button></div>
            </form>
          )}

          {step === 5 && (
            <div className="grid gap-4">
              <dl className="grid grid-cols-[10rem_1fr] gap-y-1.5 text-[13px]">
                <dt className="text-muted">Administrator</dt><dd>{admin.name} &lt;{admin.email}&gt;</dd>
                <dt className="text-muted">Application URL</dt><dd>{app.base_url}</dd>
                <dt className="text-muted">Timezone</dt><dd>{app.timezone}</dd>
                <dt className="text-muted">Approval policy</dt><dd>{sec.default_approval_policy.replace('_', ' ').toLowerCase()}</dd>
              </dl>
              <div className="flex justify-between">
                <Button variant="ghost" onClick={() => setStep(4)}>Back</Button>
                <Button disabled={busy} onClick={() => run(async () => {
                  const r = await api.post<{ csrf_token: string | null }>('/setup/complete', { token, admin: { name: admin.name, email: admin.email, password: admin.password }, base_url: app.base_url, timezone: app.timezone, security: sec });
                  setCsrf(r.csrf_token);
                  qc.setQueryData(['setup-status'], { setup_required: false });
                  await qc.invalidateQueries({ queryKey: ['me'] });
                  navigate('/', { replace: true });
                })}>{busy ? 'Completing…' : 'Complete installation'}</Button>
              </div>
            </div>
          )}

          {error && <p role="alert" className="mt-4 text-[13px] text-danger">{error}</p>}
        </CardContent>
      </Card>
    </AuthLayout>
  );
}
